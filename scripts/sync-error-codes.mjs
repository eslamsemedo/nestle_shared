// Reads the backend's ErrorCode enum and writes the ErrorCode string union.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const backend = process.env.BACKEND_DIR ?? path.resolve(repoRoot, '../nestle_backend');
const source = path.join(backend, 'app/Enums/ErrorCode.php');
const target = path.join(repoRoot, 'src/generated/error-codes.ts');

const php = readFileSync(source, 'utf8');
const codes = [...php.matchAll(/^\s*case\s+\w+\s*=\s*'([A-Z0-9_]+)';/gm)].map((m) => m[1]);
const unique = [...new Set(codes)];

if (unique.length === 0) {
  throw new Error(`No error codes found in ${source}`);
}

const body = [
  '// Generated by scripts/sync-error-codes.mjs from nestle_backend/app/Enums/ErrorCode.php. Do not edit.',
  '',
  'export type ErrorCode =',
  ...unique.map((code, i) => `  | '${code}'${i === unique.length - 1 ? ';' : ''}`),
  '',
].join('\n');

writeFileSync(target, body);
console.log(`Wrote ${unique.length} error codes to ${path.relative(repoRoot, target)}`);
