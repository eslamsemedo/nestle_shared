// Reads the permission list from the backend seeder and writes the Permission string union.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const backend = process.env.BACKEND_DIR ?? path.resolve(repoRoot, '../nestle_backend');
const source = path.join(backend, 'database/seeders/RolesAndPermissionsSeeder.php');
const target = path.join(repoRoot, 'src/generated/permissions.ts');

const php = readFileSync(source, 'utf8');

// Only the `$permissions = [ ... ];` block defines permissions; role arrays below repeat them.
const start = php.indexOf('$permissions = [');
const end = php.indexOf('];', start);
if (start === -1 || end === -1) {
  throw new Error(`Could not find the $permissions block in ${source}`);
}

const block = php
  .slice(start, end)
  .split('\n')
  .filter((line) => !line.trim().startsWith('//'))
  .join('\n');

const permissions = [...new Set([...block.matchAll(/'([a-z_]+(?:\.[a-z_]+)+)'/g)].map((m) => m[1]))].sort();

if (permissions.length === 0) {
  throw new Error(`No permissions found in ${source}`);
}

const body = [
  '// Generated by scripts/sync-permissions.mjs from RolesAndPermissionsSeeder.php. Do not edit.',
  '',
  'export type Permission =',
  ...permissions.map((p, i) => `  | '${p}'${i === permissions.length - 1 ? ';' : ''}`),
  '',
].join('\n');

writeFileSync(target, body);
console.log(`Wrote ${permissions.length} permissions to ${path.relative(repoRoot, target)}`);
